#!/usr/bin/env python3
"""Extract patch 7116's put-hook lines from the tree's runtime/ppu/ppu_loader.cpp for the host test.

Usage: put_hook_lines.py PPU_LOADER_CPP OUT_H

The walker test (test_gcm_put_snap.c) must run the real hook lines of the out-of-line vm_write32 / vm_write64, not a
copy. This script takes every statement line in those two functions that names g_gcm_put_ea / g_gcm_put_hook, checks
that they come after the OOB / null-store return and before the store lands (VM_WRITE_COH), and writes them verbatim
(with #line, so a compile error points at ppu_loader.cpp) into two C functions:
    static void loader_put_hook_w32(uint64_t a, uint32_t v);   // vm_write32's hook lines
    static void loader_put_hook_w64(uint64_t a, uint64_t v);   // vm_write64's hook lines
Exit 1 when a function or its hook lines are missing or out of order (the tree without patch 7116 fails here).
"""
import re
import sys

FUNCS = (
    ("vm_write32", r"^void vm_write32\(uint64_t a, uint32_t v\)", "loader_put_hook_w32", "uint32_t"),
    ("vm_write64", r"^void vm_write64\(uint64_t a, uint64_t v\)", "loader_put_hook_w64", "uint64_t"),
)


def body(lines, sig):
    """-> [(line number, text)] of the function whose signature matches sig, up to the next top-level item."""
    start = next((i for i, t in enumerate(lines) if re.match(sig, t)), None)
    if start is None:
        return None
    out = [(start + 1, lines[start])]
    for i in range(start + 1, len(lines)):
        t = lines[i]
        if t.startswith("void ") or t.startswith("}") or t.startswith("extern ") or t.startswith("static "):
            break
        out.append((i + 1, t))
    return out


def main(argv):
    if len(argv) != 3:
        print(__doc__.strip().splitlines()[2], file=sys.stderr)
        return 2
    src, dst = argv[1], argv[2]
    with open(src, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()
    parts = ["/* Generated by port/rc/tests/put_hook_lines.py from %s: patch 7116's hook lines, verbatim. */" % src]
    for name, sig, fn, vtype in FUNCS:
        b = body(lines, sig)
        if not b:
            print(f"put_hook_lines: FAIL: {name} not found in {src}", file=sys.stderr)
            return 1
        hook = [(n, t) for n, t in b if "g_gcm_put_" in t and not t.lstrip().startswith(("/*", "*", "//"))]
        if not hook:
            print(f"put_hook_lines: FAIL: no g_gcm_put_ea / g_gcm_put_hook line in {name} (tree without patch 7116?)",
                  file=sys.stderr)
            return 1
        guard = [n for n, t in b if "vm_oob(" in t]
        store = [n for n, t in b if "VM_WRITE_COH(" in t]
        if not guard or not store:
            print(f"put_hook_lines: FAIL: {name}: no vm_oob guard or no VM_WRITE_COH store", file=sys.stderr)
            return 1
        if not (guard[0] < hook[0][0] and hook[-1][0] < store[0]):
            print(f"put_hook_lines: FAIL: {name}: hook lines {hook[0][0]}-{hook[-1][0]} are not between the OOB guard "
                  f"(l.{guard[0]}) and the store (l.{store[0]}): the hook must see the old put", file=sys.stderr)
            return 1
        if hook[-1][0] - hook[0][0] + 1 != len(hook):
            print(f"put_hook_lines: FAIL: {name}: hook lines are not contiguous ({[n for n, _ in hook]})",
                  file=sys.stderr)
            return 1
        parts.append(f"static void {fn}(uint64_t a, {vtype} v)\n{{")
        parts.append(f'#line {hook[0][0]} "{src}"')
        parts.extend(t for _, t in hook)
        parts.append("}")
        print(f"put_hook_lines: {name}: l.{hook[0][0]}-{hook[-1][0]} ({len(hook)} line(s))")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(parts) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
